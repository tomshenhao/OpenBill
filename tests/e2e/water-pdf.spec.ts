import AxeBuilder from "@axe-core/playwright";
import { expect, test } from "@playwright/test";
import { waterPdfCopy } from "../../src/i18n/water-pdf";
import { messages } from "../../src/i18n/index";
import { syntheticPdf } from "../fixtures/electricity-bills";
import { watercareFixture } from "../fixtures/watercare-pdf";

for (const locale of ["en", "zh"] as const) test(`${locale}: Watercare PDF review, calculation, correction and privacy`, async ({ page, context, baseURL }) => {
  const t = waterPdfCopy[locale], manual = messages[locale].water;
  const home = locale === "en" ? "/water/" : "/zh/water/";
  const requests: { path: string; allowed: boolean }[] = [];
  const logs: string[] = [];
  await context.route("**/*", async (route) => {
    const request = route.request(), url = new URL(request.url());
    const allowed = url.origin === baseURL && !url.search && request.method() === "GET" && request.postData() === null &&
      (url.pathname === home || url.pathname === "/icon.svg" || url.pathname.startsWith("/_next/static/") || url.pathname === "/_openbill/pdf.worker.mjs");
    requests.push({ path: url.pathname, allowed });
    if (allowed) await route.continue(); else await route.abort();
  });
  page.on("console", (message) => logs.push(message.text()));
  page.on("pageerror", (error) => logs.push(error.message));
  await page.goto(home);
  await expect(page.getByRole("button", { name: t.start, exact: true })).toHaveAttribute("aria-pressed", "true");
  await expect(page.locator("#water-occupants")).toHaveCount(0);
  await page.getByLabel(t.file, { exact: true }).setInputFiles({ name: "synthetic-watercare.pdf", mimeType: "application/pdf", buffer: watercareFixture({ estimated: locale === "zh" }) });
  const preview = page.getByRole("region", { name: t.preview, exact: true });
  await expect(preview.getByRole("heading", { name: t.preview })).toBeFocused();
  await expect(preview.getByRole("status")).toHaveText(t.extracted);
  for (const value of ["114.81", "94.81", "12.34 kL", "30", "411.33 L"]) await expect(preview.getByText(new RegExp(value))).toBeVisible();
  await expect(page.locator("#water-pdf-waterRate")).toHaveCount(1);
  await expect(page.locator("#water-pdf-waterRate")).toBeHidden();
  await expect(page.locator("#water-pdf-occupants")).toBeVisible();
  await page.getByText(t.review, { exact: true }).click();
  const fields = { days: "30", kl: "12.34", dailyLitres: "411", waterRate: "2.15", waterAmount: "26.53", wastewaterPercent: "78.5", wastewaterKl: "9.69",
    wastewaterRate: "3.95", wastewaterAmount: "38.28", annualFixedRate: "365", fixedAmount: "30.00", gst: "12.37", currentCharges: "94.81", amountDue: "114.81",
    invoiceDate: "2 Jun 2026", dueDate: "20 Jun 2026", previousDate: "1 May 2026", currentDate: "31 May 2026" } as const;
  for (const [field, value] of Object.entries(fields)) await expect(page.locator(`#water-pdf-${field}`)).toHaveValue(value);
  await expect(page.getByText(t.dateFormat, { exact: false })).toHaveCount(0);
  const dueDate = page.locator("#water-pdf-dueDate");
  await dueDate.fill("invalid");
  await expect(dueDate).toHaveAccessibleDescription(`${t.invalid} ${t.dateFormat}`);
  await dueDate.fill(fields.dueDate);
  await expect(page.getByText(t.dateFormat, { exact: false })).toHaveCount(0);
  await expect(page.getByLabel(t.file, { exact: true })).toHaveValue("");
  await expect(page.getByLabel(t.reading)).toHaveValue(locale === "zh" ? "estimated" : "actual");
  const analyse = page.getByRole("button", { name: t.confirm });
  const summary = page.getByRole("region", { name: t.results });
  await expect(summary).toHaveCount(0);
  await page.getByLabel(t.occupants, { exact: true }).first().fill("3");
  await expect(summary).toHaveCount(0);
  await analyse.click();
  await expect(summary.getByRole("heading", { name: t.results, exact: true })).toBeFocused();
  await expect(preview).toHaveCount(0);
  await expect(summary.getByText(t.meets)).toBeVisible();
  await expect(summary.getByText("137.11")).toBeVisible();
  await expect(summary.getByText(t.historical)).toBeVisible();
  await expect(summary.getByText(locale === "zh" ? manual.estimatedNote : manual.actualNote)).toBeVisible();
  await expect(summary.locator("dl").first().getByText(/114\.81/)).toBeVisible();
  await expect(summary.locator('time[datetime="2026-06-20"]')).toHaveText("20 Jun 2026");
  await summary.getByText(t.verification, { exact: true }).click();
  await expect(summary.getByRole("row", { name: new RegExp(t.fields.amountDue) })).toContainText("114.81");
  await expect(summary.getByTestId("water-pdf-verification")).toHaveText(t.reconciles);
  await expect(page.locator("#water-pdf-waterRate")).toBeHidden();
  await page.setViewportSize({ width: 320, height: 800 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect((await new AxeBuilder({ page }).include('[aria-label="' + t.start + '"]').withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()).violations).toEqual([]);
  await page.getByText(t.review, { exact: true }).click();
  await page.locator("#water-pdf-days").fill("31");
  await analyse.click();
  await expect(summary.getByTestId("water-pdf-verification")).toHaveText(t.periodMismatch);
  await page.locator("#water-pdf-days").fill("30");
  await page.locator("#water-pdf-kl").fill("14.85");
  await analyse.click();
  await expect(summary.getByText(t.near)).toBeVisible();
  await expect(summary.getByTestId("water-pdf-verification")).toHaveText(t.differs);
  expect(requests.every((request) => request.allowed)).toBe(true);
  expect(requests.filter((request) => request.path.endsWith("/pdf.worker.mjs"))).toHaveLength(1);
  expect(logs).toEqual([]);
  await expect(page.locator("body")).not.toContainText("SYNTHETIC-CUSTOMER");
  expect(await context.cookies()).toEqual([]);
  expect(await page.evaluate(async () => [localStorage.length, sessionStorage.length, (await indexedDB.databases()).length, (await caches.keys()).length])).toEqual([0, 0, 0, 0]);
  await page.getByRole("button", { name: t.reset }).click();
  await expect(summary).toHaveCount(0);
  await expect(page.locator("#water-pdf-kl")).toHaveCount(0);
  await page.getByLabel(t.file, { exact: true }).setInputFiles({ name: "synthetic-watercare.pdf", mimeType: "application/pdf", buffer: watercareFixture() });
  await expect(page.locator("#water-pdf-kl")).toHaveValue("12.34");
  await page.reload();
  await expect(page.locator("#water-pdf-kl")).toHaveCount(0);
});

test("Watercare rejects scanned, unsupported and malformed PDFs and preserves manual fallback", async ({ page }) => {
  const t = waterPdfCopy.en;
  await page.goto("/water/");
  const pdfPanel = page.getByRole("region", { name: t.start, exact: true });
  const file = page.getByLabel(t.file, { exact: true });
  for (const [buffer, message] of [[syntheticPdf([[]]), t.errors.image], [syntheticPdf([["Unfamiliar layout"]]), t.errors.unsupported], [Buffer.from("%PDF-bad"), t.errors.invalid]] as const) {
    await file.setInputFiles({ name: "synthetic.pdf", mimeType: "application/pdf", buffer });
    await expect(pdfPanel.getByRole("alert")).toHaveText(message);
  }
  await page.getByRole("button", { name: t.fallback }).click();
  await expect(page.locator("#water-occupants")).toBeFocused();
  await expect(file).toHaveCount(0);
  await page.getByRole("button", { name: t.start }).click();
  await file.setInputFiles({ name: "synthetic.pdf", mimeType: "application/pdf", buffer: syntheticPdf([["Watercare", "Water consumption $7.01", "Balance of current charges $8.23"]]) });
  await expect(page.locator("#water-pdf-kl")).toBeVisible();
  await page.locator("#water-pdf-occupants").fill("3");
  await page.getByRole("button", { name: t.confirm }).click();
  await expect(page.locator("#water-pdf-days")).toBeFocused();
  await expect(page.getByTestId("water-pdf-verification")).toHaveCount(0);
  await file.setInputFiles({ name: "synthetic.pdf", mimeType: "application/pdf", buffer: watercareFixture({ conflicting: true }) });
  await expect(page.locator("#water-pdf-waterAmount")).toHaveValue("");
  await expect(page.locator("#water-pdf-waterAmount")).toBeVisible();
  await expect(page.getByText(t.uncertain)).toBeVisible();
  await page.locator("#water-pdf-occupants").fill("3");
  await page.getByRole("button", { name: t.confirm }).click();
  await expect(page.getByTestId("water-pdf-verification")).toHaveText(t.incomplete);
  await page.locator("#water-pdf-waterAmount").fill("26.53");
  await page.getByRole("button", { name: t.confirm }).click();
  await expect(page.getByTestId("water-pdf-verification")).toHaveText(t.reconciles);
  await page.getByRole("button", { name: t.manualMode }).click();
  await expect(page.locator("#water-occupants")).toBeFocused();
  await expect(page.locator("#water-pdf-kl")).toHaveCount(0);
  await page.getByRole("button", { name: t.start, exact: true }).click();
  await expect(page.locator("#water-occupants")).toHaveCount(0);
  await expect(page.locator("#water-pdf-occupants")).toHaveCount(0);
  await expect(file).toHaveValue("");
});
