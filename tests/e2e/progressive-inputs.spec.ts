import AxeBuilder from "@axe-core/playwright";
import { expect, test } from "@playwright/test";
import { messages } from "../../src/i18n/index";
import { openAdvancedBill } from "./journey-helpers";

for (const locale of ["en", "zh"] as const) test(`${locale}: usage first, keyboard period choice and separate data-blocked pricing`, async ({ page }) => {
  const t = messages[locale].analysis;
  await page.goto(locale === "en" ? "/electricity/" : "/zh/electricity/");
  await page.waitForLoadState("networkidle");
  const requests: string[] = [], logs: string[] = []; page.on("request", (r) => requests.push(r.url())); page.on("console", (m) => logs.push(m.text()));
  const status = page.locator("#usage-input-status"), usage = page.getByTestId("usage-rating");
  await expect(status).toHaveAttribute("role", "status");
  await expect(status).toHaveText(t.journey.requirements.kwh);
  await expect(page.locator("#price-step")).not.toBeVisible();
  for (const id of ["bill-days", "bill-totalNzd", "bill-gst", "bill-meter", "bill-usageCents", "bill-peak"]) await expect(page.locator(`#${id}`)).not.toBeVisible();
  await page.locator("#bill-kwh").fill("223"); await expect(status).toHaveText(t.journey.requirements.region);
  await page.locator("#bill-region").selectOption("NZ-AUK"); await expect(status).toHaveText(t.journey.requirements.dates);
  await page.getByRole("radio", { name: t.journey.datesMode, exact: true }).focus(); await page.keyboard.press("ArrowRight");
  await expect(page.getByRole("radio", { name: t.journey.monthMode, exact: true })).toBeChecked();
  await expect(page.locator("#bill-start")).toHaveCount(0); await expect(page.locator("#bill-end")).toHaveCount(0);
  await expect(status).toHaveText(t.journey.requirements.month);
  await page.locator("#bill-month").selectOption("2026-06"); await expect(status).toHaveText(t.journey.requirements.confirmation);
  await page.getByLabel(t.fullMonth, { exact: true }).check();
  await expect(usage).toHaveAttribute("data-rating", "green"); await expect(page.getByTestId("usage-days")).toHaveText("30");
  await expect(page.getByRole("button", { name: t.calculate, exact: true })).not.toBeVisible();
  await page.getByText(t.journey.context, { exact: true }).click();
  await expect(page.getByText(t.journey.householdHint, { exact: true })).toBeVisible();
  await page.locator("#bill-people").fill("6"); await expect(usage).toHaveAttribute("data-rating", "green");
  await page.locator("#bill-month").selectOption("2026-07"); await expect(status).toHaveText(t.journey.requirements.confirmation);
  await expect(usage).toHaveAttribute("data-rating", "unknown"); await page.getByLabel(t.fullMonth, { exact: true }).check();
  const next = page.getByRole("button", { name: t.journey.next, exact: true }); await next.focus(); await page.keyboard.press("Enter");
  await expect(page.locator("#price-step-heading")).toBeFocused(); await expect(next).toHaveAttribute("aria-expanded", "true");
  await expect(page.getByTestId("supplier-data-limitation")).toHaveText(t.journey.noPriceInputs);
  await expect(page.getByTestId("price-rating").locator("input,select")).toHaveCount(0);
  await expect(page.locator("#bill-totalNzd")).not.toBeVisible();
  await openAdvancedBill(page, t); await page.locator("#bill-totalNzd").fill("invalid");
  await page.getByRole("button", { name: t.calculate, exact: true }).click(); await expect(page.locator("#bill-error")).toBeFocused();
  await expect(usage).toHaveAttribute("data-rating", "green");
  await page.getByRole("radio", { name: t.journey.datesMode, exact: true }).check();
  await page.locator("#bill-start").fill("2026-09-01"); await page.locator("#bill-end").fill("2026-09-30");
  await expect(status).toHaveText(t.journey.requirements["missing-data"]); await expect(usage).toHaveAttribute("data-rating", "unknown");
  const accessibility = await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa", "wcag22aa"]).analyze(); expect(accessibility.violations).toEqual([]);
  expect(requests).toEqual([]); expect(logs).toEqual([]);
  expect(await page.evaluate(() => ({ local: localStorage.length, session: sessionStorage.length, cookies: document.cookie, fits: document.documentElement.scrollWidth <= innerWidth }))).toEqual({ local: 0, session: 0, cookies: "", fits: true });
  await page.getByRole("button", { name: t.clear, exact: true }).click(); await expect(page.locator("#price-step")).not.toBeVisible();
  await expect(status).toHaveText(t.journey.requirements.kwh);
});
